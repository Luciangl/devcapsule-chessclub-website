// Run inside firebase emulators:exec after preparing demo-rocada-spark.
import assert from 'node:assert/strict';
import { publicOrigin } from '../hosting.mjs';
process.argv[2] = 'http://127.0.0.1:5000';
process.argv[3] = publicOrigin(process.env.FIREBASE_SITE_URL ?? 'https://demo-rocada-spark.web.app');
await import('../check-http.mjs');
const origin = process.argv[2];
const home = await fetch(origin);
assert.match(home.headers.get('cache-control'), /max-age=300/);
const html = await home.text();
const asset = html.match(/(?:src|href)="(\/_astro\/[^"?]+)"/)?.[1];
assert.ok(asset, 'generated asset found');
const cached = await fetch(new URL(asset, origin));
assert.equal(cached.status, 200);
assert.match(cached.headers.get('cache-control'), /max-age=31536000, immutable/);
const news = await fetch(`${origin}/noutati/`);
assert.equal(news.status, 200);
const article = (await news.text()).match(/href="(\/noutati\/[^"/]+\/)"/)?.[1];
assert.ok(article, 'article route found');
assert.equal((await fetch(new URL(article, origin))).status, 200);
console.log('HTML and asset cache headers, archive and article routes verified.');
